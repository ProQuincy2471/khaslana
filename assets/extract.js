/* ===========================================================================
   KHASLANA — chapter extraction, shared by both readers

   The Node indexer and the browser's live scan must agree exactly about what
   a chapter *is*, so the rules live here once and both load this file:
   `scripts/index-codex.mjs` requires it, index.html loads it as a script.

   Chapters generated by /master-enarm carry the whole thing as JSON inside
   <script id="topic-data">. Everything below reads that; the HTML fallback
   only exists for a file that somehow lacks it.
   =========================================================================== */

(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.KHASLANA_EXTRACT = api;
})(typeof self !== 'undefined' ? self : this, function () {

  const AREAS = [
    { id: 'mi',            label: 'Medicina Interna',
      keys: ['medicina interna', 'cardiolog', 'neumolog', 'nefrolog', 'endocrin', 'hematolog',
        'reumatolog', 'gastroenterolog', 'neurolog', 'geriatr', 'oncolog', 'inmunolog'] },
    { id: 'cirugia',       label: 'Cirugía',
      keys: ['cirug', 'quirurg', 'quirúrg', 'trauma', 'ortoped', 'urolog', 'anestesi', 'proctolog'] },
    { id: 'gineco',        label: 'Ginecología y Obstetricia',
      keys: ['ginecolog', 'obstetric', 'perinat', 'materno'] },
    { id: 'pedia',         label: 'Pediatría',
      keys: ['pediatr', 'neonatolog', 'infantil'] },
    { id: 'infecto',       label: 'Infectología',
      keys: ['infectolog', 'microbiolog', 'parasitolog', 'virolog'] },
    { id: 'urgencias',     label: 'Urgencias y Cuidados Críticos',
      keys: ['urgencias', 'cuidados criticos', 'cuidados críticos', 'terapia intensiva',
        'medicina critica', 'medicina crítica', 'reanimac', 'toxicolog'] },
    { id: 'farmaco',       label: 'Farmacología',
      keys: ['farmacolog', 'farmacia', 'terapeutica', 'terapéutica'] },
    { id: 'psiquiatria',   label: 'Psiquiatría',
      keys: ['psiquiatr', 'salud mental', 'psicolog'] },
    { id: 'salud-publica', label: 'Salud Pública y Bioética',
      keys: ['salud publica', 'salud pública', 'epidemiolog', 'bioestadist', 'bioestadíst',
        'bioetica', 'bioética', 'medicina legal', 'medicina familiar', 'genero', 'género',
        'violencia', 'maltrato', 'abuso', 'derechos'] },
    { id: 'otras-esp',     label: 'Dermato · Oftalmo · ORL',
      keys: ['dermatolog', 'oftalmolog', 'otorrinolaringolog', 'otorrino', 'audiolog'] },
  ];

  const CONTENT_HINTS = {
    infecto: ['bacteri', 'virus', 'viral', 'antibiótic', 'antibiotic', 'antimicrobian', 'vacuna',
      'contagios', 'incubación', 'serolog', 'cultivo', 'patógeno', 'sepsis', 'micosis'],
    gineco: ['embarazo', 'gestación', 'parto', 'puerperio', 'útero', 'ovario', 'cérvix', 'mama'],
    pedia: ['lactante', 'neonato', 'recién nacido', 'preescolar', 'escolar', 'prematuro'],
    cirugia: ['abordaje quirúrgico', 'laparotom', 'laparoscop', 'anastomosis', 'resección'],
    mi: ['hipertensión', 'diabetes', 'insuficiencia cardiaca', 'creatinina', 'electrolito'],
  };

  function scoreAreas(specialty, trunk, content) {
    const scores = {};
    for (const a of AREAS) scores[a.id] = 0;

    const segs = String(specialty || '').split(/[\/,·|]/).map(x => x.trim().toLowerCase()).filter(Boolean);
    segs.forEach((seg, i) => {
      const w = i === 0 ? 30 : 10;
      for (const a of AREAS) if (a.keys.some(kk => seg.includes(kk))) scores[a.id] += w;
    });

    const tr = String(trunk || '').toLowerCase();
    for (const a of AREAS) if (a.keys.some(kk => tr.includes(kk))) scores[a.id] += 8;

    for (const id of Object.keys(CONTENT_HINTS)) {
      for (const h of CONTENT_HINTS[id]) if (content.includes(h)) scores[id] += 1;
    }

    let best = null, bestScore = 0;
    for (const a of AREAS) if (scores[a.id] > bestScore) { bestScore = scores[a.id]; best = a; }
    return best && bestScore >= 3
      ? { area: best.id, areaLabel: best.label }
      : { area: 'otros', areaLabel: 'Otros' };
  }

  const decodeEntities = (s) => s
    .replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'");

  const stripTags = (s) => decodeEntities(String(s).replace(/<[^>]*>/g, ' ')).replace(/\s+/g, ' ').trim();
  const deacc = (s) => String(s).normalize('NFD').replace(/[̀-ͯ]/g, '');
  const clean = (s) => String(s).replace(/\*\*|__|`/g, '').replace(/\s+/g, ' ').trim();

  /* Flatten any block shape (prose, table, flow, case…) into plain words. */
  function flatten(node, out, depth) {
    depth = depth || 0;
    if (depth > 8 || out.length > 600) return;
    if (typeof node === 'string') { out.push(node); return; }
    if (Array.isArray(node)) { for (const n of node) flatten(n, out, depth + 1); return; }
    if (node && typeof node === 'object') {
      for (const k of Object.keys(node)) {
        if (k === 'color' || k === 'icon' || k === 'id' || k === 'type') continue;
        flatten(node[k], out, depth + 1);
      }
    }
  }

  function extract(html, fallbackName) {
    const m = html.match(/<script[^>]*id=["']topic-data["'][^>]*>([\s\S]*?)<\/script>/i);
    if (m) {
      let D = null;
      try { D = JSON.parse(m[1]); } catch (e) { D = null; }
      if (D) {
        const blocks = Array.isArray(D.blocks) ? D.blocks : [];
        const sections = [];
        for (const b of blocks) {
          const t = clean(b.title || '');
          if (t && sections.indexOf(t) === -1) sections.push(t);
        }
        const bits = [];
        flatten(blocks, bits);
        return {
          title: clean(D.topic || D.title || fallbackName).replace(/^[^\wÀ-ÿ]+/, '').replace(/_/g, ' '),
          subtitle: clean(D.subtitle || ''),
          source: clean(D.source || ''),
          specialty: clean(D.specialty || ''),
          trunk: clean(D.trunk || ''),
          aliases: Array.isArray(D.aliases) ? D.aliases.map(clean) : [],
          sections: sections,
          cases: blocks.filter(b => b.type === 'case').length,
          tables: blocks.filter(b => b.type === 'table').length,
          flows: blocks.filter(b => b.type === 'flow' || b.type === 'branch' || b.type === 'nodes').length,
          body: clean(bits.join(' ')).toLowerCase(),
          rich: true,
        };
      }
    }

    /* Fallback: scrape headings if a chapter has no structured data. */
    const stripped = html
      .replace(/<style[\s\S]*?<\/style>/gi, ' ')
      .replace(/<script[\s\S]*?<\/script>/gi, ' ')
      .replace(/<svg[\s\S]*?<\/svg>/gi, ' ');
    const t = html.match(/<title[^>]*>([\s\S]*?)<\/title>/i);
    const sections = [];
    const re = /<h([1-4])[^>]*>([\s\S]*?)<\/h\1>/gi;
    let h;
    while ((h = re.exec(stripped)) !== null) {
      const txt = stripTags(h[2]);
      if (txt && txt.length > 2 && txt.length < 140 && sections.indexOf(txt) === -1) sections.push(txt);
    }
    return {
      title: t ? stripTags(t[1]) : fallbackName,
      subtitle: '', source: '', specialty: '', trunk: '', aliases: [],
      sections: sections, cases: 0, tables: 0, flows: 0,
      body: stripTags(stripped).toLowerCase().slice(0, 4000),
      rich: false,
    };
  }

  /* One chapter, from raw HTML to the shape the app stores. */
  function toEntry(html, file, extras) {
    const base = file.replace(/\.html$/i, '');
    const x = extract(html, base);
    const content = [x.subtitle, x.aliases.join(' '), x.sections.join(' '), x.body].join(' ').toLowerCase();
    const a = scoreAreas(x.specialty, x.trunk, content);

    return Object.assign({
      id: base.replace(/[^\w]+/g, '-').toLowerCase(),
      title: x.title,
      subtitle: x.subtitle,
      file: file,
      rel: 'codex/' + encodeURIComponent(file),
      area: a.area,
      areaLabel: a.areaLabel,
      specialty: x.specialty,
      trunk: x.trunk,
      aliases: x.aliases,
      sections: x.sections.slice(0, 30),
      cases: x.cases,
      tables: x.tables,
      flows: x.flows,
      source: x.source,
      haystack: deacc(x.title + ' ' + x.subtitle + ' ' + x.aliases.join(' ') + ' ' +
                      x.specialty + ' ' + x.sections.join(' ') + ' ' + x.body)
                .toLowerCase().slice(0, 24000),
      rich: x.rich,
    }, extras || {});
  }

  return { AREAS: AREAS, extract: extract, toEntry: toEntry, scoreAreas: scoreAreas, deacc: deacc };
});
